// TestKeygenWritesOwnerOnlyKeyFile checks the key file mode and the overwrite refusal.
func TestKeygenWritesOwnerOnlyKeyFile(t *testing.T) {
	directory := t.TempDir()
	keyFilePath := filepath.Join(directory, "key.json")
	stdout := &bytes.Buffer{}
	if err := ExecuteCodecServerCommand(context.Background(), []string{"keygen", "-o", keyFilePath}, stdout, io.Discard); err != nil {
		t.Fatal(err)
	}
	assertOwnerOnly(t, keyFilePath)
	if _, err := NewLocalCodecFromKeyFile(keyFilePath); err != nil {
		t.Fatalf("generated key file does not load: %v", err)
	}
	original, err := os.ReadFile(keyFilePath)
	if err != nil {
		t.Fatal(err)
	}
	err = ExecuteCodecServerCommand(context.Background(), []string{"keygen", "-o", keyFilePath}, io.Discard, io.Discard)
	if err == nil || !strings.Contains(err.Error(), "already exists") {
		t.Fatalf("second keygen error = %v, want a refusal", err)
	}
	unchanged, err := os.ReadFile(keyFilePath)
	if err != nil || !bytes.Equal(unchanged, original) {
		t.Fatal("refused keygen changed the key file")
	}
	if err := os.Chmod(keyFilePath, 0o644); err != nil {
		t.Fatal(err)
	}
	if err := ExecuteCodecServerCommand(context.Background(), []string{"keygen", "-o", keyFilePath, "-force", "-key-id", "k2"}, io.Discard, io.Discard); err != nil {
		t.Fatal(err)
	}
	assertOwnerOnly(t, keyFilePath)
	replaced, err := os.ReadFile(keyFilePath)
	if err != nil || bytes.Equal(replaced, original) || !strings.Contains(string(replaced), `"current_key_id": "k2"`) {
		t.Fatalf("forced keygen did not replace the key: %s", replaced)
	}
}

func assertOwnerOnly(t *testing.T, path string) {
	t.Helper()
	info, err := os.Stat(path)
	if err != nil {
		t.Fatal(err)
	}
	if info.Mode().Perm() != 0o600 {
		t.Fatalf("%s has mode %v, want 0600", path, info.Mode().Perm())
	}
}
