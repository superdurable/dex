const testWebOrigin = "http://127.0.0.1:8802"

type runningCodecServer struct {
	endpoint    string
	token       string
	keyFilePath string
}

// startTestCodecServer serves a key file generated by keygen on a real 127.0.0.1 listener.
func startTestCodecServer(t *testing.T) runningCodecServer {
	t.Helper()
	keyFilePath := filepath.Join(t.TempDir(), "key.json")
	if err := GenerateKeyFile(keyFilePath, "dev-key", false); err != nil {
		t.Fatal(err)
	}
	codec, err := NewLocalCodecFromKeyFile(keyFilePath)
	if err != nil {
		t.Fatal(err)
	}
	token, err := NewLocalCodecServerToken()
	if err != nil {
		t.Fatal(err)
	}
	listener, err := net.Listen("tcp", "127.0.0.1:0")
	if err != nil {
		t.Fatal(err)
	}
	server, err := NewLocalCodecServer(codec, token, []string{testWebOrigin}, listener)
	if err != nil {
		t.Fatal(err)
	}
	go func() { _ = server.Serve(listener) }()
	t.Cleanup(func() { _ = server.Close() })
	return runningCodecServer{endpoint: "http://" + listener.Addr().String(), token: token, keyFilePath: keyFilePath}
}

func sdkCodec(t *testing.T, keyFilePath string) dex.PayloadCodec {
	t.Helper()
	keys, err := dex.NewFilePayloadEncryptionKeyProvider(keyFilePath)
	if err != nil {
		t.Fatal(err)
	}
	codec, err := dex.NewAESGCMPayloadCodec(keys, dex.AESGCMPayloadCodecOptions{})
	if err != nil {
		t.Fatal(err)
	}
	return codec
}

func interopValues() []*dexpb.Value {
	return []*dexpb.Value{
		{Kind: &dexpb.Value_StringValue{StringValue: "hello"}},
		{Kind: &dexpb.Value_IntValue{IntValue: -7}},
		{Kind: &dexpb.Value_DoubleValue{DoubleValue: 2.5}},
		{Kind: &dexpb.Value_BoolValue{BoolValue: true}},
		{Kind: &dexpb.Value_ObjValue{ObjValue: &dexpb.EncodedObject{Encoding: "json", Payload: []byte(`{"order":"A-1"}`)}}},
	}
}

type codecHTTPResult struct {
	status int
	header http.Header
	body   map[string]any
}

func postCodecJSON(t *testing.T, server runningCodecServer, path string, body string, headers map[string]string) codecHTTPResult {
	t.Helper()
	request, err := http.NewRequest(http.MethodPost, server.endpoint+path, strings.NewReader(body))
	if err != nil {
		t.Fatal(err)
	}
	request.Header.Set("Content-Type", "application/json")
	for name, value := range headers {
		if name == "Host" {
			request.Host = value
			continue
		}
		request.Header.Set(name, value)
	}
	return doCodecRequest(t, request)
}

func doCodecRequest(t *testing.T, request *http.Request) codecHTTPResult {
	t.Helper()
	response, err := http.DefaultClient.Do(request)
	if err != nil {
		t.Fatal(err)
	}
	defer response.Body.Close()
	content, err := io.ReadAll(response.Body)
	if err != nil {
		t.Fatal(err)
	}
	result := codecHTTPResult{status: response.StatusCode, header: response.Header, body: map[string]any{}}
	if len(content) > 0 {
		if err := json.Unmarshal(content, &result.body); err != nil {
			t.Fatalf("response %d is not JSON: %s", response.StatusCode, content)
		}
	}
	return result
}

func bearer(token string) map[string]string {
	return map[string]string{"Authorization": "Bearer " + token}
}

func errorCategory(result codecHTTPResult) string {
	failure, _ := result.body["error"].(map[string]any)
	category, _ := failure["category"].(string)
	return category
}

// TestLocalCodecServerDecodesGoSDKEnvelopes checks that the server and the Go SDK read each other's envelopes.
func TestLocalCodecServerDecodesGoSDKEnvelopes(t *testing.T) {
	server := startTestCodecServer(t)
	codec := sdkCodec(t, server.keyFilePath)
	payloadContext := dex.PayloadContext{FlowType: "OrderFlow", FlowID: "order-1"}
	plaintexts := make([][]byte, 0)
	for _, value := range interopValues() {
		plaintext, err := proto.Marshal(value)
		if err != nil {
			t.Fatal(err)
		}
		plaintexts = append(plaintexts, plaintext)
	}
	envelopes, err := codec.Encode(context.Background(), payloadContext, plaintexts)
	if err != nil {
		t.Fatal(err)
	}
	encodedEnvelopes := make([]string, 0, len(envelopes))
	for _, envelope := range envelopes {
		envelopeBytes, err := proto.Marshal(envelope)
		if err != nil {
			t.Fatal(err)
		}
		encodedEnvelopes = append(encodedEnvelopes, base64.StdEncoding.EncodeToString(envelopeBytes))
	}
	requestBody, err := json.Marshal(map[string]any{
		"context":   map[string]string{"flow_type": "OrderFlow", "flow_id": "order-1"},
		"envelopes": encodedEnvelopes,
	})
	if err != nil {
		t.Fatal(err)
	}
	result := postCodecJSON(t, server, "/decode", string(requestBody), bearer(server.token))
	if result.status != http.StatusOK {
		t.Fatalf("decode status %d body %v", result.status, result.body)
	}
	decodedValues := result.body["values"].([]any)
	for index, expected := range interopValues() {
		valueJSON, err := json.Marshal(decodedValues[index])
		if err != nil {
			t.Fatal(err)
		}
		decoded := &dexpb.Value{}
		if err := protojson.Unmarshal(valueJSON, decoded); err != nil {
			t.Fatal(err)
		}
		if !proto.Equal(decoded, expected) {
			t.Fatalf("value %d decoded to %v, want %v", index, decoded, expected)
		}
	}
}

func TestLocalCodecServerEncodesEnvelopesForGoSDK(t *testing.T) {
	server := startTestCodecServer(t)
	remote, err := NewRemoteCodec(server.endpoint, server.token)
	if err != nil {
		t.Fatal(err)
	}
	payloadContext := dex.PayloadContext{FlowID: "order-1"}
	envelopes, err := remote.EncodeValues(context.Background(), payloadContext, interopValues())
	if err != nil {
		t.Fatal(err)
	}
	parsed := make([]*dexpb.PayloadEnvelope, 0, len(envelopes))
	for _, envelopeBytes := range envelopes {
		envelope := &dexpb.PayloadEnvelope{}
		if err := proto.Unmarshal(envelopeBytes, envelope); err != nil {
			t.Fatal(err)
		}
		if envelope.GetKeyId() != "dev-key" || envelope.GetCipher() != dexpb.PayloadCipher_PAYLOAD_CIPHER_AES256_GCM {
			t.Fatalf("unexpected envelope header %v", envelope)
		}
		parsed = append(parsed, envelope)
	}
	plaintexts, err := sdkCodec(t, server.keyFilePath).Decode(context.Background(), payloadContext, parsed)
	if err != nil {
		t.Fatal(err)
	}
	for index, expected := range interopValues() {
		decoded := &dexpb.Value{}
		if err := proto.Unmarshal(plaintexts[index], decoded); err != nil {
			t.Fatal(err)
		}
		if !proto.Equal(decoded, expected) {
			t.Fatalf("value %d decoded to %v, want %v", index, decoded, expected)
		}
	}
	values, err := remote.DecodeEnvelopes(context.Background(), payloadContext, envelopes)
	if err != nil || !proto.Equal(values[4], interopValues()[4]) {
		t.Fatalf("remote round trip = %v, %v", values, err)
	}
}

func TestLocalCodecServerReportsEntryErrors(t *testing.T) {
	server := startTestCodecServer(t)
	remote, err := NewRemoteCodec(server.endpoint, server.token)
	if err != nil {
		t.Fatal(err)
	}
	envelopes, err := remote.EncodeValues(context.Background(), dex.PayloadContext{FlowID: "f"}, interopValues()[:1])
	if err != nil {
		t.Fatal(err)
	}
	unknownKey := &dexpb.PayloadEnvelope{}
	if err := proto.Unmarshal(envelopes[0], unknownKey); err != nil {
		t.Fatal(err)
	}
	unknownKey.KeyId = "missing-key"
	unknownKeyBytes, err := proto.Marshal(unknownKey)
	if err != nil {
		t.Fatal(err)
	}
	for _, scenario := range []struct {
		name     string
		path     string
		body     string
		status   int
		category string
		index    float64
	}{
		{"unknown key names its entry", "/decode", fmt.Sprintf(`{"context":{"flow_type":"","flow_id":"f"},"envelopes":[%q,%q]}`,
			base64.StdEncoding.EncodeToString(envelopes[0]), base64.StdEncoding.EncodeToString(unknownKeyBytes)), http.StatusUnprocessableEntity, "unknown_key", 1},
		{"unpadded base64", "/decode", `{"context":{"flow_type":"T","flow_id":"f"},"envelopes":["abc"]}`, http.StatusUnprocessableEntity, "malformed", 0},
		{"reserved encoding", "/encode", `{"context":{"flow_type":"T","flow_id":"f"},"values":[{"stringValue":"ok"},{"objValue":{"encoding":"dex/1","payload":"AA=="}}]}`, http.StatusUnprocessableEntity, "invalid_plaintext", 1},
		{"missing flow id", "/encode", `{"context":{"flow_type":"T"},"values":[]}`, http.StatusBadRequest, "malformed", -1},
		{"not JSON", "/encode", `{`, http.StatusBadRequest, "malformed", -1},
		{"too many entries", "/decode", `{"context":{"flow_type":"T","flow_id":"f"},"envelopes":[` + strings.TrimSuffix(strings.Repeat(`"",`, maxCodecRequestEntries+1), ",") + `]}`, http.StatusRequestEntityTooLarge, "limit_exceeded", -1},
	} {
		t.Run(scenario.name, func(t *testing.T) {
			result := postCodecJSON(t, server, scenario.path, scenario.body, bearer(server.token))
			if result.status != scenario.status || errorCategory(result) != scenario.category {
				t.Fatalf("status %d body %v, want %d %s", result.status, result.body, scenario.status, scenario.category)
			}
			index, hasIndex := result.body["error"].(map[string]any)["index"].(float64)
			if scenario.index < 0 && hasIndex || scenario.index >= 0 && index != scenario.index {
				t.Fatalf("error index = %v, want %v", result.body["error"], scenario.index)
			}
		})
	}
	result := postCodecJSON(t, server, "/encode", `{"context":{"flow_type":"T","flow_id":"f"},"values":[]}`, bearer(server.token))
	if result.status != http.StatusOK || len(result.body["envelopes"].([]any)) != 0 {
		t.Fatalf("empty encode = %d %v", result.status, result.body)
	}
}

// TestLocalCodecServerRejectsUntrustedRequests checks the Host, token, and CORS protections.
func TestLocalCodecServerRejectsUntrustedRequests(t *testing.T) {
	server := startTestCodecServer(t)
	_, port, err := net.SplitHostPort(strings.TrimPrefix(server.endpoint, "http://"))
	if err != nil {
		t.Fatal(err)
	}
	body := `{"context":{"flow_type":"T","flow_id":"f"},"values":[{"stringValue":"x"}]}`
	for _, scenario := range []struct {
		name     string
		headers  map[string]string
		status   int
		category string
	}{
		{"missing token", map[string]string{}, http.StatusUnauthorized, CategoryUnauthenticated},
		{"wrong token", bearer("not-the-token"), http.StatusUnauthorized, CategoryUnauthenticated},
		{"rebound host name", map[string]string{"Authorization": "Bearer " + server.token, "Host": "attacker.example:" + port}, http.StatusForbidden, CategoryForbidden},
		{"localhost on another port", map[string]string{"Authorization": "Bearer " + server.token, "Host": "localhost:1"}, http.StatusForbidden, CategoryForbidden},
		{"origin not allowed", map[string]string{"Authorization": "Bearer " + server.token, "Origin": "http://attacker.example"}, http.StatusForbidden, CategoryForbidden},
	} {
		t.Run(scenario.name, func(t *testing.T) {
			result := postCodecJSON(t, server, "/encode", body, scenario.headers)
			if result.status != scenario.status || errorCategory(result) != scenario.category {
				t.Fatalf("status %d body %v, want %d %s", result.status, result.body, scenario.status, scenario.category)
			}
			if result.header.Get("Access-Control-Allow-Origin") != "" {
				t.Fatalf("rejected request allowed CORS: %v", result.header)
			}
		})
	}

	result := postCodecJSON(t, server, "/encode", body, map[string]string{
		"Authorization": "Bearer " + server.token, "Origin": testWebOrigin, "Host": "localhost:" + port,
	})
	if result.status != http.StatusOK || result.header.Get("Access-Control-Allow-Origin") != testWebOrigin {
		t.Fatalf("allowed origin: status %d header %v body %v", result.status, result.header, result.body)
	}

	preflight, err := http.NewRequest(http.MethodOptions, server.endpoint+"/decode", nil)
	if err != nil {
		t.Fatal(err)
	}
	preflight.Header.Set("Origin", testWebOrigin)
	preflight.Header.Set("Access-Control-Request-Method", "POST")
	preflight.Header.Set("Access-Control-Request-Headers", "authorization, content-type")
	preflightResult := doCodecRequest(t, preflight)
	if preflightResult.status != http.StatusNoContent ||
		preflightResult.header.Get("Access-Control-Allow-Origin") != testWebOrigin ||
		!strings.Contains(preflightResult.header.Get("Access-Control-Allow-Headers"), "Authorization") {
		t.Fatalf("preflight: status %d header %v", preflightResult.status, preflightResult.header)
	}
	preflight.Header.Set("Origin", "http://attacker.example")
	if rejected := doCodecRequest(t, preflight); rejected.status != http.StatusForbidden {
		t.Fatalf("preflight from another origin: status %d", rejected.status)
	}
}

