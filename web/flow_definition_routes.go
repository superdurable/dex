// maxRequestedFlowTypeBytes bounds the Flow type a browser may ask for; Dex Servers allow far less.
const maxRequestedFlowTypeBytes = 1024

// flowTypeDefinitionsResponse is every definition of one Flow type, with graphs.
type flowTypeDefinitionsResponse struct {
	FlowType           string              `json:"flowType"`
	DefinitionRevision string              `json:"definitionRevision"`
	Definitions        []flowDefinition    `json:"definitions"`
	V2                 *api.V2CatalogEntry `json:"v2"`
}

func newVisualizeFlowDefinitionSources(graph []byte) (flowDefinitionSources, error) {
	sources := flowDefinitionSources{
		memory:         []flowDefinitionDocument{{origin: flowDefinitionOriginVisualize, path: "visualized-flow.json", data: graph}},
		memoryLocation: "generated by dexcli visualize",
	}
	snapshot, err := sources.Load(context.Background())
	if err != nil {
		return flowDefinitionSources{}, err
	}
	if err := firstFlowDefinitionError(snapshot); err != nil {
		return flowDefinitionSources{}, err
	}
	return sources, nil
}

// serveFlowDefinitions lists every definition without its graph, for pages that list definitions.
func serveFlowDefinitions(provider flowDefinitionLookup) http.HandlerFunc {
	return func(response http.ResponseWriter, request *http.Request) {
		snapshot, err := provider.Load(request.Context())
		if err != nil {
			writeFlowDefinitionSourceError(response, err)
			return
		}
		setSnapshotETag(response, snapshot.DefinitionRevision)
		response.Header().Set("Content-Type", "application/json; charset=utf-8")
		response.WriteHeader(http.StatusOK)
		if _, err := response.Write(snapshot.metadataResponse); err != nil {
			panic(fmt.Sprintf("write Flow Definition Graph catalog: %v", err))
		}
	}
}

// serveFlowTypeDefinitions returns the definitions of one Flow type, so a run page reads only its own.
// It answers 304 when If-None-Match names the current revision.
func serveFlowTypeDefinitions(provider flowDefinitionLookup) http.HandlerFunc {
	return func(response http.ResponseWriter, request *http.Request) {
		flowType := request.PathValue("flowType")
		if flowType == "" || len(flowType) > maxRequestedFlowTypeBytes || !utf8.ValidString(flowType) {
			api.WriteCodedError(response, http.StatusBadRequest, "FLOW_TYPE_INVALID", "Flow type is empty, too long, or not UTF-8")
			return
		}
		snapshot, err := provider.loadFlowTypes(request.Context(), []string{flowType})
		if err != nil {
			writeFlowDefinitionSourceError(response, err)
			return
		}
		revision, found := snapshot.flowTypeRevisions[flowType]
		if !found {
			api.WriteCodedError(response, http.StatusNotFound, "FLOW_DEFINITION_NOT_FOUND", "No Flow definition declares this Flow type")
			return
		}
		setSnapshotETag(response, revision)
		response.Header().Set("Cache-Control", "no-cache")
		if requestMatchesETag(request, revision) {
			response.WriteHeader(http.StatusNotModified)
			return
		}
		body := flowTypeDefinitionsResponse{FlowType: flowType, DefinitionRevision: revision, Definitions: []flowDefinition{}}
		for _, definition := range snapshot.definitions {
			if definition.FlowName == flowType {
				body.Definitions = append(body.Definitions, definition)
			}
		}
		if definition, ok := snapshot.V2Definitions[flowType]; ok {
			entry := api.NewV2CatalogEntry(flowType, definition, revision)
			body.V2 = &entry
		}
		writeWebJSON(response, http.StatusOK, body)
	}
}

// serveFlowDefinitionTypes names every Flow type with a definition; it reads no uploaded content.
func serveFlowDefinitionTypes(provider flowDefinitionLookup) http.HandlerFunc {
	return func(response http.ResponseWriter, request *http.Request) {
		list, err := provider.listFlowTypes(request.Context())
		if err != nil {
			writeFlowDefinitionSourceError(response, err)
			return
		}
		writeWebJSON(response, http.StatusOK, list)
	}
}

func requestMatchesETag(request *http.Request, revision string) bool {
	quoted := fmt.Sprintf("%q", revision)
	for _, candidate := range strings.Split(request.Header.Get("If-None-Match"), ",") {
		if strings.TrimSpace(candidate) == quoted {
			return true
		}
	}
	return false
}

func v2DefinitionSnapshot(snapshot *FlowDefinitionSnapshot) api.V2DefinitionSnapshot {
	return api.V2DefinitionSnapshot{
		Definitions:       snapshot.V2Definitions,
		Revision:          snapshot.DefinitionRevision,
		FlowTypeRevisions: snapshot.flowTypeRevisions,
	}
}

// revision changes whenever a Flow type is added, removed, or moves between sources.
func (list *flowDefinitionTypeList) revision() string {
	parts := make([]string, 0, 2*len(list.FlowTypes))
	for _, name := range list.FlowTypes {
		parts = append(parts, name.Source, name.FlowType)
	}
	return framedDigest(parts)
}
